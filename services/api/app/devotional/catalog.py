@dataclass(frozen=True)
class CatalogItem:
    theme: str
    ref: str


@cache
def catalog() -> list[CatalogItem]:
    return [CatalogItem(theme, ref) for theme, refs in PASSAGES.items() for ref in refs]


@cache
def year_order(year: int) -> list[CatalogItem]:
    """Uma passagem por dia do ano (366, contando os anos bissextos), sem repetir no ano.
    Cada ano tem uma ordem diferente, sempre a mesma para o mesmo ano."""
    items = list(catalog())
    random.Random(year).shuffle(items)  # noqa: S311 (não é uso criptográfico)
    return items


def item_for_day(day: date) -> CatalogItem:
    return year_order(day.year)[day.timetuple().tm_yday - 1]


def reference(ref: str) -> Reference:
    return parse(ref, "en")[0]


# ---------- Planos de leitura ----------


@dataclass(frozen=True)
class Plan:
    code: str
    category: str  # whole | testament | book | topical
    title: dict[str, str]
    description: dict[str, str]
    days: list[list[str]]  # cada dia: referências ("GEN 1-3", "JHN 2:1-11")


def _chapters(codes: list[str]) -> list[tuple[str, int]]:
    out = []
    for code in codes:
        book = by_code()[code]
        out.extend((code, c) for c in range(1, book.chapters + 1))
    return out


def _spread(chapters: list[tuple[str, int]], days: int) -> list[list[str]]:
    """Distribui capítulos de forma uniforme e agrupa capítulos seguidos do mesmo livro."""
    n = len(chapters)
    result = []
    for d in range(days):
        chunk = chapters[d * n // days : (d + 1) * n // days]
        refs: list[str] = []
        i = 0
        while i < len(chunk):
            book, first = chunk[i]
            last = first
            while i + 1 < len(chunk) and chunk[i + 1][0] == book and chunk[i + 1][1] == last + 1:
                i += 1
                last = chunk[i][1]
            refs.append(f"{book} {first}" if first == last else f"{book} {first}-{last}")
            i += 1
        result.append(refs)
    return result


def _codes(start: str, end: str) -> list[str]:
    codes = [b.code for b in all_books()]
    return codes[codes.index(start) : codes.index(end) + 1]


